#!/usr/bin/env python3
"""Export the pinned Linux Perfetto C SDK's GN declarations to the Zig build.

GN is used only to refresh committed declarations. Normal builds compile the
SDK and its three protoc plugins with Zig, sharing the existing AOSP protobuf.
No Ninja build or downloaded Perfetto buildtools are needed for this export.
"""
import argparse
import collections
import json
from pathlib import Path
import subprocess
import tempfile

PROFILE = (
    "is_debug=false is_clang=false is_perfetto_embedder=true "
    "enable_perfetto_ipc=true enable_perfetto_zlib=false "
    "is_perfetto_build_generator=true use_custom_libcxx=false "
    "perfetto_enable_git_rev_version_header=false"
)
ROOT_TARGET = "//src/shared_lib:libperfetto_c"
BEGIN = "// BEGIN GENERATED PERFETTO NATIVE DECLARATIONS"
END = "// END GENERATED PERFETTO NATIVE DECLARATIONS"


def quoted(value):
    return json.dumps(value)


def array(name, values, indent=""):
    return (f"{indent}{name}{{\n" +
            "".join(f"{indent}    {quoted(v)},\n" for v in values) + f"{indent}}};\n")


def export(description, sources_file, declarations_file):
    def closure(root):
        seen = set()
        def visit(label):
            if label in seen or description[label]["type"] == "executable":
                return
            seen.add(label)
            for dependency in description[label].get("deps", []):
                visit(dependency)
        visit(root)
        return seen

    runtime = closure(ROOT_TARGET)
    base = closure("//src/base:base")
    output = ["// Generated by tools/gen-perfetto-sources.py from pinned Perfetto GN.\n",
              "// Linux, in-process and system IPC tracing; no Android daemon dependency.\n\n",
              "pub const SourceGroup = struct { files: []const []const u8, defines: []const []const u8 };\n\n"]
    for name, labels in (("base", base), ("sdk", runtime - base)):
        groups = collections.defaultdict(set)
        for label in labels:
            target = description[label]
            if target["type"] not in ("source_set", "static_library", "shared_library"):
                continue
            for source in target.get("sources", []):
                if not source.endswith((".c", ".cc", ".cpp")):
                    continue
                defines = tuple(target.get("defines", []))
                if not source.startswith("//"):
                    assert "/gen/protos/" in source, source
                    assert defines == ("NDEBUG", "PERFETTO_IMPLEMENTATION"), (source, defines)
                    continue
                assert not source.startswith("//buildtools/"), source
                groups[defines].add(source[2:])
        output.append(f"pub const {name} = [_]SourceGroup{{\n")
        for defines, files in sorted(groups.items()):
            output.append("    .{ .defines = &.{ " + ", ".join(map(quoted, defines)) + " }, .files = &.{\n")
            output.extend(f"        {quoted(source)},\n" for source in sorted(files))
            output.append("    } },\n")
        output.append("};\n\n")
    output.append("pub const Plugin = struct { name: []const u8, source: []const u8 };\n")
    output.append("pub const plugins = [_]Plugin{\n")
    for label in sorted(description):
        target = description[label]
        if target["type"] == "executable" and label.endswith("_plugin"):
            source, = target["sources"]
            output.append(f"    .{{ .name = {quoted(label.split(':')[-1])}, .source = {quoted(source[2:])} }},\n")
    output.append("};\n")
    sources_file.write_text("".join(output))

    groups = collections.defaultdict(set)
    for label in runtime:
        target = description[label]
        if target["type"] != "action" or target.get("script") != "//gn/standalone/protoc.py":
            continue
        plugin, = [a.split("=")[-1] for a in target["args"] if a.startswith("--plugin=")]
        options, = [a.split("--plugin_out=")[1].split(":")[0]
                    for a in target["args"] if a.startswith("--plugin_out=")]
        assert plugin in ("cppgen_plugin", "protozero_plugin", "ipc_plugin"), plugin
        expected_suffix = {"cppgen_plugin": ".gen", "protozero_plugin": ".pbzero", "ipc_plugin": ".ipc"}[plugin]
        expected = {s[2:-6] + expected_suffix + extension for s in target["sources"]
                    for extension in (".h", ".cc")}
        assert expected == {s.split("/gen/")[1] for s in target["outputs"]}, label
        groups[plugin, options, expected_suffix].update(s[2:] for s in target["sources"])
    block = [BEGIN + "\n", "// Refreshed by tools/gen-perfetto-sources.py; expected outputs use each input's\n",
             "// stem plus the declared suffix and .h/.cc, as in the pinned proto_library.gni.\n",
             "pub const PerfettoNativeProto = struct {\n",
             "    plugin: []const u8, options: []const u8, suffix: []const u8, inputs: []const []const u8,\n",
             "};\n",
             "pub const perfetto_native_protos = [_]PerfettoNativeProto{\n"]
    for (plugin, options, suffix), inputs in sorted(groups.items()):
        block.append(f"    .{{ .plugin = {quoted(plugin)}, .options = {quoted(options)}, .suffix = {quoted(suffix)}, .inputs = &.{{\n")
        block.extend(f"        {quoted(source)},\n" for source in sorted(inputs))
        block.append("    } },\n")
    block.append("};\n")
    block.append(array("pub const perfetto_native_build_flags = [_][]const u8", description["//gn:gen_buildflags"]["response_file_contents"][1:]))
    block.append(END + "\n")
    current = declarations_file.read_text()
    if BEGIN in current:
        start = current.index(BEGIN)
        end = current.index(END, start) + len(END) + 1
        current = current[:start] + "".join(block) + current[end:]
    else:
        anchor = "/// Perfetto's framework javastream library"
        assert anchor in current
        current = current.replace(anchor, "".join(block) + "\n" + anchor, 1)
    declarations_file.write_text(current)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", type=Path, help="Pinned external/perfetto checkout")
    parser.add_argument("--description", type=Path, help="Use an existing GN JSON description")
    parser.add_argument("--sources", type=Path, default=Path("build/gen/perfetto_sources.zig"))
    parser.add_argument("--declarations", type=Path, default=Path("build/generator_sources.zig"))
    args = parser.parse_args()
    if args.description:
        description = json.loads(args.description.read_text())
    else:
        with tempfile.TemporaryDirectory(prefix="perfetto-gn-") as out:
            common = ["--root=" + str(args.root.resolve()), "--root-target=" + ROOT_TARGET]
            subprocess.run(["gn", "gen", out, *common, "--args=" + PROFILE], check=True)
            description = json.loads(subprocess.check_output(
                ["gn", "desc", out, "//*", *common, "--format=json", "--all-toolchains"], text=True))
    export(description, args.sources, args.declarations)
    subprocess.run(["zig", "fmt", str(args.sources), str(args.declarations)], check=True)


if __name__ == "__main__":
    main()
