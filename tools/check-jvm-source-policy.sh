#!/usr/bin/env bash
# JVM source provenance gate. Two rules:
#   1. Repository-owned JVM sources (.java AND .kt) may only live in the
#      allowlisted directories.
#   2. No repository-owned class may shadow a class we now GENERATE: a file
#      whose package+name matches a generated aconfig/logtags artifact (derived
#      from the generator input lists, so this ratchets automatically as more
#      generators land) is rejected — it must come from generation, not by hand.
# The extracted AOSP package has no nested Git metadata; build.zig.zon's package
# hash is its revision/content pin.
set -euo pipefail
cd "$(dirname "$0")/.."
AOSP_ROOT=${1:?usage: check-jvm-source-policy.sh <extracted-aosp-root>}

status=0

# --- 1. directory allowlist (now covers .kt, which the old gate never saw) ---
while IFS= read -r source; do
    [[ -e "$source" ]] || continue
    case "$source" in
        artzig/src/gen/*) ;;                 # generated repository outputs
        artzig/examples/*) ;;                # directly reused Android example source
        src/framework/*|src/framework-stubs/*) ;; # AOSP-facing compatibility sources
        src/java/*) ;;                       # repo-owned app/system code (dev.artzig)
        src/annotation-runtime/*) ;;         # android.annotation markers (separate javac pass)
        src/testkit/*|tests/*) ;;            # test helpers/fixtures
        testdata/kotlin-shadow/*) ;;         # javac fixtures for Kotlin runtime shadowing
        *)
            printf 'repository-owned JVM source is not allowed here: %s\n' "$source" >&2
            status=1
            ;;
    esac
done < <(git ls-files '*.java' '*.kt')

# --- 2. no hand-written class in a package we generate -----------------------
# Forbidden = <pkg-path>/<Class>.{java,kt} for every generated artifact. The
# lists are the same inputs the generators consume, so adding a package here
# (as a deferred generator lands) automatically forbids its hand-written stub.
forbidden=$(mktemp)
trap 'rm -f "$forbidden"' EXIT

# aconfig: each package emits Flags + the FeatureFlags family.
while IFS='|' read -r pkg _container _source _declarations; do
    case "$pkg" in \#*|'') continue ;; esac
    d="${pkg//.//}"
    for c in Flags FeatureFlags FeatureFlagsImpl CustomFeatureFlags FakeFeatureFlagsImpl; do
        printf '%s/%s.java\n%s/%s.kt\n' "$d" "$c" "$d" "$c" >> "$forbidden"
    done
done < tools/aconfig-inputs.txt

# logtags: the EventLogTags class in each source's java_package.
while IFS='|' read -r source rel output; do
    case "$source" in \#*|'') continue ;; esac
    base=${output%.java}
    printf '%s.java\n%s.kt\n' "$base" "$base" >> "$forbidden"
done < tools/logtags-list.txt

# sysprop: the accessor class named by each declaration's `module` (its FQN).
while IFS='|' read -r scope source rel; do
    case "$scope" in \#*|'') continue ;; esac
    [ "$source" = aosp ] || continue
    src="$AOSP_ROOT/$rel"
    [ -f "$src" ] || continue
    fqn=$(sed -n 's/^module:[[:space:]]*"\([A-Za-z0-9_.]*\)".*/\1/p' "$src" | head -1)
    [ -n "$fqn" ] && printf '%s.java\n%s.kt\n' "${fqn//.//}" "${fqn//.//}" >> "$forbidden"
done < tools/sysprop-list.txt

# stats: the generated atom-logging class.
printf '%s\n' com/android/internal/util/FrameworkStatsLog.java \
    com/android/internal/util/FrameworkStatsLog.kt >> "$forbidden"

# javanano: the nano message classes (tools/nano-list.txt outer classes).
printf '%s\n' com/android/internal/logging/nano/MetricsProto.java \
    com/android/internal/logging/nano/MetricsProto.kt >> "$forbidden"

# proto: every javastream message class (package/<Message>.java), from the .proto
# files generated by protoc-gen-javastream. All framework protos use java_package
# == the proto `package` with java_multiple_files, so each message (nested too)
# lands at <package>/<Message>.java.
while IFS='|' read -r source rel; do
    case "$source" in \#*|'') continue ;; esac
    [ "$source" = aosp ] || continue
    src="$AOSP_ROOT/$rel"
    [ -f "$src" ] || continue
    pkg=$(sed -n 's/^package[[:space:]]\+\([A-Za-z0-9_.]*\);.*/\1/p' "$src" | head -1)
    [ -n "$pkg" ] || continue
    d="${pkg//.//}"
    sed -n 's/^[[:space:]]*message[[:space:]]\+\([A-Za-z0-9_]*\).*/\1/p' "$src" | while read -r m; do
        printf '%s/%s.java\n%s/%s.kt\n' "$d" "$m" "$d" "$m" >> "$forbidden"
    done
done < tools/proto-list.txt

for root in src/framework-stubs src/framework; do
    while IFS= read -r rel; do
        if grep -qxF "$rel" "$forbidden"; then
            printf 'hand-written class shadows a generated one (must be generated): %s/%s\n' "$root" "$rel" >&2
            status=1
        fi
    done < <(cd "$root" && git ls-files '*.java' '*.kt' 2>/dev/null)
done

# --- 2b. no unmarked duplicate of a vendored AOSP class ----------------------
# A repo-owned android.*/com.android.* class whose FQN also exists in packaged
# AOSP source tree must either be generated/reused (rule 2) or be a declared
# host adaptation: its first 20 lines must carry an `artzig` marker or the
# `Hosted adaptation of AOSP` header.
aosp_index=$(mktemp)
trap 'rm -f "$forbidden" "$aosp_index"' EXIT
find "$AOSP_ROOT/frameworks/base" "$AOSP_ROOT/frameworks/libs/modules-utils" \
    "$AOSP_ROOT/packages/modules/StatsD" -type f \( -name '*.java' -o -name '*.kt' \) \
    | grep -vE '/tests?/|/androidTest/' > "$aosp_index"

for root in src/framework-stubs src/framework; do
    while IFS= read -r rel; do
        case "$rel" in android/*|com/android/*) ;; *) continue ;; esac
        esc=$(printf '%s' "$rel" | sed 's/[.[\*^$]/\\&/g')
        grep -qE "(^|/)$esc$" "$aosp_index" || continue
        head -20 "$root/$rel" | grep -qE 'artzig|Hosted adaptation of AOSP' && continue
        printf 'unmarked duplicate of a vendored AOSP class (reuse it, or mark the host seam): %s/%s
' "$root" "$rel" >&2
        status=1
    done < <(cd "$root" && git ls-files '*.java' '*.kt' 2>/dev/null)
done

exit "$status"
