#!/usr/bin/env python3
"""gen-skia-sources.py — turn a `gn gen --ide=json` project.json of skia into
build/gen/skia_sources.zig (source groups + per-group flags + defines + libs).

Usage: tools/gen-skia-sources.py <project.json> <out.zig>
The gn args used live in tools/regen-skia.sh; this mirrors skia's own
gn/gn_to_bp.py approach (Android.bp is generated from gn the same way)."""
import json, sys

proj, out = sys.argv[1], sys.argv[2]
t = json.load(open(proj))["targets"]

# Transitive deps of //:skia that carry sources. Older stock Skia exposed an
# extra //:pathops target; AOSP's graph folds it into //:skia.
seen, stack = set(), ["//:skia"]
if "//:pathops" in t:
    stack.append("//:pathops")
while stack:
    n = stack.pop()
    if n in seen:
        continue
    seen.add(n)
    stack.extend(t[n].get("deps", []))

SRC_EXT = (".cpp", ".cc", ".c")
DROP_DEFINES = {
    "SK_HIDE_PATH_EDIT_METHODS",  # legacy SkPath layout (matches hwui)
    "SK_DISABLE_TRACING",        # framework mode traces via cutils ATrace
    "SK_R32_SHIFT=16",           # Android's bitmap ABI uses RGBA on Linux too
}
ADD_DEFINES = ["SK_BUILD_FOR_ANDROID", "__ANDROID_API__=36", "SK_GAMMA_CONTRAST=0.0",
               "SK_GAMMA_EXPONENT=1.4", "SK_BUILD_FOR_ANDROID_FRAMEWORK", "SK_SUPPORT_LEGACY_EMBOSSMASKFILTER",
               "SK_R32_SHIFT=0"]

defines, libs, groups = set(), [], []
for n in sorted(seen):
    x = t[n]
    srcs = [s[2:] for s in x.get("sources", []) if s.endswith(SRC_EXT)]
    # Match BUILD.gn's Android logging port for SK_BUILD_FOR_ANDROID.
    srcs = ["src/ports/SkDebug_android.cpp" if s == "src/ports/SkDebug_stdio.cpp" else s
            for s in srcs]
    for d in x.get("defines", []):
        if d not in DROP_DEFINES:
            defines.add(d)
    for l in x.get("libs", []) or []:
        if l not in libs:
            libs.append(l)
    if not srcs:
        continue
    flags = [c for c in x.get("cflags", []) if c.startswith("-m")]
    groups.append((n, srcs, flags))

def zstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

with open(out, "w") as f:
    f.write("//! GENERATED by tools/gen-skia-sources.py — do not edit.\n")
    f.write("//! Skia source groups for build/skia.zig (paths relative to external/skia).\n\n")
    f.write("pub const Group = struct { name: []const u8, files: []const []const u8, flags: []const []const u8 };\n\n")
    f.write("pub const defines = [_][]const u8{\n")
    for d in sorted(defines) + ADD_DEFINES:
        f.write(f"    {zstr(d)},\n")
    f.write("};\n\n")
    f.write("pub const system_libs = [_][]const u8{\n")
    for l in libs:
        f.write(f"    {zstr(l)},\n")
    f.write("};\n\n")
    f.write("pub const groups = [_]Group{\n")
    for n, srcs, flags in groups:
        f.write(f"    .{{ .name = {zstr(n)}, .flags = &.{{ {', '.join(zstr(x) for x in flags)} }}, .files = &.{{\n")
        for s in sorted(srcs):
            f.write(f"        {zstr(s)},\n")
        f.write("    } },\n")
    f.write("};\n")
print(f"{out}: {len(groups)} groups, {sum(len(g[1]) for g in groups)} sources, {len(defines)+len(ADD_DEFINES)} defines, libs={libs}")
