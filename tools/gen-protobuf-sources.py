#!/usr/bin/env python3
"""gen-protobuf-sources.py — turn the vendored protobuf cmake source lists into
build/gen/protobuf_sources.zig (relative .cc paths for libprotobuf and libprotoc).
Mirrors tools/gen-skia-sources.py: a committed generated source list so the zig
build owns the library, compiled with one toolchain (libc++) — ABI-consistent
with the zig-built generator tools that link it.

Usage: gen-protobuf-sources.py <protobuf-cmake-dir> <out.zig>
"""
import re, sys

cmake_dir, out = sys.argv[1], sys.argv[2]


def files(name):
    """Relative google/protobuf/*.cc paths from a set(<name> ...) block."""
    text = open(f"{cmake_dir}/{name}").read()
    return sorted(set(re.findall(r"google/protobuf/[A-Za-z0-9_/]+\.cc", text)))


# The full library links the lite sources plus the full-only sources.
full = files("libprotobuf-lite.cmake") + [
    f for f in files("libprotobuf.cmake") if f not in files("libprotobuf-lite.cmake")
]
protoc = files("libprotoc.cmake")

with open(out, "w") as f:
    f.write("// Generated by tools/gen-protobuf-sources.py from the vendored\n")
    f.write("// protobuf cmake source lists. Do not edit by hand.\n\n")
    for var, lst in (("libprotobuf", full), ("libprotoc", protoc)):
        f.write(f"pub const {var} = [_][]const u8{{\n")
        for s in sorted(set(lst)):
            f.write(f'    "{s}",\n')
        f.write("};\n\n")
