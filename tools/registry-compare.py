#!/usr/bin/env python3
"""Compare the hosted SystemServiceRegistry with AOSP's.

Prints a Markdown table of every service name either registry registers: the
binder name, the AOSP client class, and what the hosted registry provides for it
(the verbatim AOSP client, a stub client, an initializer-registered client, or
nothing). Run from the repository root with a built framework jar:

    tools/registry-compare.py [framework-classes.jar] > docs/service-registry.md
"""
import glob
import os
import re
import subprocess
import sys
import zipfile

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AOSP_REGISTRY = os.path.join(REPO, "aosp/frameworks/base/core/java/android/app/SystemServiceRegistry.java")
HOSTED_REGISTRY = os.path.join(REPO, "src/framework/android/app/SystemServiceRegistry.java")
CONTEXT = os.path.join(REPO, "aosp/frameworks/base/core/java/android/content/Context.java")
STUBS = os.path.join(REPO, "src/framework-stubs")

# Clients AOSP registers through a framework initializer that the hosted registry runs.
INITIALIZER_CLIENTS = {
    "TELEPHONY_SERVICE": "TelephonyManager",
    "TELEPHONY_SUBSCRIPTION_SERVICE": "SubscriptionManager",
    "CARRIER_CONFIG_SERVICE": "CarrierConfigManager",
    "EUICC_SERVICE": "EuiccManager",
    "EUICC_CARD_SERVICE": "EuiccCardManager",
    "TELEPHONY_IMS_SERVICE": "ImsManager",
    "SMS_SERVICE": "SmsManager",
    "SATELLITE_SERVICE": "SatelliteManager",
    "MEDIA_SESSION_SERVICE": "MediaSessionManager",
}


def registrations(source):
    out = {}
    for m in re.finditer(r"registerService\(Context\.([A-Z_]+),\s*([\w.]+)\.class", source):
        out[m.group(1)] = m.group(2)
    return out


def qualify(name, aosp_src, hosted_src):
    if "." in name:
        return name
    for src in (hosted_src, aosp_src):
        m = re.search(r"import ([\w.]+\." + re.escape(name) + r");", src)
        if m:
            return m.group(1)
    return "android.app." + name


def main():
    jar = sys.argv[1] if len(sys.argv) > 1 else max(glob.glob(os.path.join(REPO, ".zig-cache/o/*/framework-classes.jar")), key=os.path.getmtime)
    classes = set(zipfile.ZipFile(jar).namelist())
    stubs = set()
    for dp, _, fs in os.walk(STUBS):
        for f in fs:
            stubs.add(os.path.relpath(os.path.join(dp, f), STUBS).rsplit(".", 1)[0])
    aosp_src = open(AOSP_REGISTRY).read()
    hosted_src = open(HOSTED_REGISTRY).read()
    ctx = open(CONTEXT).read()
    binder_names = {m.group(1): m.group(2) for m in re.finditer(r'public static final String ([A-Z_]+) = "([^"]+)"', ctx)}
    aosp = registrations(aosp_src)
    hosted = registrations(hosted_src)
    for name, cls in INITIALIZER_CLIENTS.items():
        hosted.setdefault(name, cls)

    def hosted_status(name):
        if name not in hosted:
            return "not registered"
        cls = hosted[name]
        path = qualify(cls, aosp_src, hosted_src).replace(".", "/")
        short = cls.split(".")[-1]
        if path in stubs:
            return f"`{short}` stub"
        if path + ".class" in classes:
            return f"`{short}` real"
        return f"`{short}` real (initializer)"

    rows = []
    for name in sorted(set(aosp) | set(hosted)):
        rows.append((name, binder_names.get(name, "?"), aosp.get(name, "-").split(".")[-1], hosted_status(name), "yes" if name in aosp else "host-only"))
    real = sum(1 for r in rows if "real" in r[3])
    stub = sum(1 for r in rows if "stub" in r[3])
    absent = sum(1 for r in rows if r[3] == "not registered")
    print("# Service registry: hosted versus AOSP")
    print()
    print("Generated by `tools/registry-compare.py` from the AOSP `SystemServiceRegistry` and the")
    print("hosted one (`src/framework/android/app/SystemServiceRegistry.java`); regenerate after a")
    print("phase changes either. A *real* hosted client is the verbatim AOSP class from the built")
    print("framework jar (over a hosted service or, where AOSP tolerates it, over no service); a")
    print("*stub* client is a `src/framework-stubs` replacement; *not registered* means")
    print("`getSystemService` returns null on this host.")
    print()
    print(f"AOSP registers {len(aosp)} services; the hosted registry registers {len(hosted)}: {real} real clients, {stub} stub clients. {absent} AOSP services are not registered.")
    print()
    print("| Context name | binder name | AOSP client | hosted client | in AOSP registry |")
    print("|---|---|---|---|---|")
    for r in rows:
        print("| %s | `%s` | `%s` | %s | %s |" % r)


if __name__ == "__main__":
    main()
