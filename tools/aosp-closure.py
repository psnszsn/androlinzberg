#!/usr/bin/env python3
"""AOSP source-closure tool for the curated framework build.

Given seed classes (the real AOSP classes that are to replace host stubs), it
walks the references of their sources (imports, same-package tokens and
fully-qualified names) against the live compiled classes directory, decides
which referenced classes are already compiled (real, generated, or an existing
stub - existing stubs count as present), and prints what has to be added for
the rest: manifest lines for aosp/androlinzberg-files.txt (including the
sibling `.aidl` declaration of every Parcelable), source lines for
build/java_sources.zig, and AIDL/aconfig entries for build/generator_sources.zig. Anything
that cannot be added by listing alone - a class with JNI natives, a class whose
source is not in the checkout, an AIDL file outside the configured include
roots, a generated class whose declaration is not wired - is reported as a
blocker.

    tools/aosp-closure.py closure --classes <dir-or-jar> [--classes ...] SEED...
    tools/aosp-closure.py audit   --classes <dir-or-jar> [--classes ...]

A SEED is a fully-qualified class name (android.app.NotificationManager) or a
checkout-relative source path. `audit` evaluates every file under
src/framework-stubs as if it were removed and classifies it (see docs/stubs.md).

The tool refuses to run without a classes directory: with a wiped cache every
class looks missing. Point --classes at the newest framework-classes.jar (or
the java-classes/kotlin-classes output directories) of a completed build, e.g.
`ls -t .zig-cache/o/*/framework-classes.jar | head -1`.
"""

