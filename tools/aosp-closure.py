def read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def proto_java_names(path: str, declaration: str) -> list[str]:
    """Pinned protobuf Java name_resolver.cc, including multiple-file messages."""
    package = re.search(r'^\s*option\s+java_package\s*=\s*"([\w.]+)"', declaration, re.M)
    if package is None:
        package = PACKAGE_RE.search(declaration)
    if package is None:
        return []
    code = strip_code(declaration)
    depth = 0
    top_level: list[tuple[str, str]] = []
    declared_names: set[str] = set()
    for match in re.finditer(r"[{}]|\b(message|enum|service)\s+(\w+)", code):
        if match.group(0) == "{":
            depth += 1
        elif match.group(0) == "}":
            depth -= 1
        else:
            kind, name = match.groups()
            declared_names.add(name)
            if depth == 0:
                top_level.append((kind, name))
    explicit = re.search(r'^\s*option\s+java_outer_classname\s*=\s*"(\w+)"', declaration, re.M)
    if explicit:
        outer = explicit.group(1)
    else:
        # helpers.cc::UnderscoresToCamelCase(..., true).
        outer = ""
        capitalize = True
        for char in Path(path).stem:
            if "a" <= char <= "z" or "A" <= char <= "Z":
                outer += char.upper() if capitalize else char
                capitalize = False
            elif "0" <= char <= "9":
                outer += char
                capitalize = True
            else:
                capitalize = True
        if outer in declared_names:
            outer += "OuterClass"
    names = [outer]
    if re.search(r"\boption\s+java_multiple_files\s*=\s*true\s*;", code):
        generic_services = re.search(r"\boption\s+java_generic_services\s*=\s*true\s*;", code)
        for kind, name in top_level:
            if kind != "service" or generic_services:
                names.append(name)
            if kind == "message":
                names.append(name + "OrBuilder")
    return [f"{package.group(1)}.{name}" for name in names]


class SourceIndex:
    """FQN -> source files of the AOSP checkout, keyed by kind (java/kt/aidl)."""

    def __init__(self, aosp: Path, cache: Path | None):
        self.aosp = aosp
        self.by_fqn: dict[str, dict[str, list[str]]] = {}
        self.aconfig: dict[str, list[str]] = {}
        if cache and cache.exists():
            try:
                data = json.loads(cache.read_text())
                if data.get("version") == INDEX_VERSION and data.get("aosp") == str(aosp):
                    self.by_fqn = data["by_fqn"]
                    self.aconfig = data["aconfig"]
                    return
            except (OSError, ValueError, KeyError):
                pass
        self.build()
        if cache:
            cache.parent.mkdir(parents=True, exist_ok=True)
            cache.write_text(json.dumps({"version": INDEX_VERSION, "aosp": str(aosp), "by_fqn": self.by_fqn, "aconfig": self.aconfig}))

    def build(self) -> None:
        by_fqn: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
        for dirpath, dirnames, filenames in os.walk(self.aosp):
            rel_dir = os.path.relpath(dirpath, self.aosp)
            # The production environment class shares a name with the test tree.
            production_ravenwood = rel_dir == "frameworks/base/core/java/com/android/internal"
            dirnames[:] = sorted(d for d in dirnames if not d.startswith(".") and
                                 (d not in SKIP_DIRS or (d == "ravenwood" and production_ravenwood)))
            sources = [f for f in filenames if f.endswith((".java", ".kt", ".aidl"))]
            for f in filenames:
                if f.endswith(".proto"):
                    declaration = read(Path(dirpath, f))
                    path = os.path.normpath(os.path.join(rel_dir, f))
                    for name in proto_java_names(f, declaration):
                        by_fqn[name]["proto"].append(path)
                if f.endswith(".logtags"):
                    package = re.search(r"^\s*option\s+java_package\s+([\w.]+)",
                                        read(Path(dirpath, f)), re.M)
                    if package:
                        by_fqn[f"{package.group(1)}.{Path(f).stem}"]["logtags"].append(
                            os.path.join(rel_dir, f))
                if f.endswith(".aconfig"):
                    m = ACONFIG_PACKAGE_RE.search(read(Path(dirpath, f)))
                    if m:
                        self.aconfig.setdefault(m.group(1), []).append(os.path.join(rel_dir, f))
            if not sources:
                continue
            # All sources of one directory share a package; read one declaration.
            pkg = None
            for f in sorted(sources):
                m = PACKAGE_RE.search(read(Path(dirpath, f)))
                if m:
                    pkg = m.group(1)
                    break
            if pkg is None:
                continue
            for f in sources:
                name, ext = os.path.splitext(f)
                by_fqn[f"{pkg}.{name}"][ext[1:]].append(os.path.join(rel_dir, f))
        self.by_fqn = {k: dict(v) for k, v in by_fqn.items()}

    def lookup(self, fqn: str) -> dict[str, list[str]]:
        # The pinned external/cronet/Android.bp defaults to stable. Never mix
        # its classes with the optional tip-of-tree implementation, including
        # types that only exist in that alternative module variant.
        sources = {kind: [path for path in paths if not path.startswith("external/cronet/tot/")]
                   for kind, paths in self.by_fqn.get(fqn, {}).items()}
        sources = {kind: paths for kind, paths in sources.items() if paths}
        # Frozen AIDL API dumps describe historical ABIs, not the source to
        # compile. Retain them only for modules without a live declaration.
        aidl = sources.get("aidl", [])
        live_aidl = [path for path in aidl if "/aidl_api/" not in path]
        if live_aidl and len(live_aidl) != len(aidl):
            return {**sources, "aidl": live_aidl}
        return sources


class Manifest:
    """aosp/androlinzberg-files.txt: which checkout paths the package carries."""

    def __init__(self, path: Path):
        self.files: set[str] = set()
        self.dirs: list[str] = []
        for line in read(path).splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) != 3 or parts[1] != "aosp":
                continue
            kind, _, p = parts
            if kind in ("F", "L", "P"):
                self.files.add(p)
            elif kind == "D":
                self.dirs.append(p.rstrip("/") + "/")

    def vendored(self, path: str) -> bool:
        return path in self.files or any(path.startswith(d) for d in self.dirs)


class SourceRules:
    """build/java_sources.zig: c.file / c.add selections, expanded to checkout paths."""

    ROOT_RE = re.compile(r'addRoot\("(\w+)",\s*(.*?)\);')
    DEP_RE = re.compile(r'Root\.dependency\(b,\s*aosp,\s*"([^"]*)"\)')
    CHILD_RE = re.compile(r'(\w+)\.child\(b,\s*"([^"]+)"\)')
    VAR_RE = re.compile(r'const\s+(\w+)\s*=\s*SourceFiles\.Root\.dependency\(b,\s*aosp,\s*"([^"]*)"\)')
    FILE_RE = re.compile(r'c\.file\("(\$\w+/[^"]+)"\)')
    ADD_RE = re.compile(r'c\.add\("(\$\w+(?:/[^"]*)?)",\s*\.\{(.*?)\}\s*\);', re.S)
    LIST_RE = re.compile(r'\.(not_names|not_paths)\s*=\s*&\.\{(.*?)\}', re.S)
    DEPTH_RE = re.compile(r'\.max_depth\s*=\s*(\d+)')

    def __init__(self, path: Path):
        text = read(path)
        roots: dict[str, str] = {}
        variables = {m.group(1): m.group(2) for m in self.VAR_RE.finditer(text)}
        for m in self.ROOT_RE.finditer(text):
            name, expr = m.group(1), m.group(2)
            dep = self.DEP_RE.search(expr)
            child = self.CHILD_RE.search(expr)
            if dep:
                roots[name] = dep.group(1)
            elif child and child.group(1) in variables:
                roots[name] = variables[child.group(1)] + "/" + child.group(2)
            elif expr.strip() in variables:
                roots[name] = variables[expr.strip()]
        self.roots = roots
        self.files: set[str] = set()
        self.trees: list[tuple[str, int | None, list[str], list[str]]] = []
        self.rules_for_exclusions: list[tuple[str, str]] = []
        for m in self.FILE_RE.finditer(text):
            p = self.expand(m.group(1))
            if p:
                self.files.add(p)
        for m in self.ADD_RE.finditer(text):
            p = self.expand(m.group(1))
            if p is None:
                continue
            opts = m.group(2)
            depth = self.DEPTH_RE.search(opts)
            lists = {"not_names": [], "not_paths": []}
            for lm in self.LIST_RE.finditer(opts):
                lists[lm.group(1)] = re.findall(r'"([^"]+)"', lm.group(2))
            self.trees.append((p.rstrip("/"), int(depth.group(1)) if depth else None, lists["not_names"], lists["not_paths"]))

    def expand(self, spec: str) -> str | None:
        m = re.match(r"\$(\w+)(?:/(.*))?$", spec)
        if not m or m.group(1) not in self.roots:
            return None
        base = self.roots[m.group(1)]
        relative = m.group(2)
        if not relative:
            return base
        return f"{base}/{relative}" if base else relative

    def spec_for(self, path: str) -> str:
        """Prefer the most specific root variable for a checkout path."""
        best = None
        for name, base in self.roots.items():
            if (not base or path.startswith(base + "/")) and (best is None or len(base) > len(self.roots[best])):
                best = name
        if best is None:
            return path
        base = self.roots[best]
        relative = path[len(base) + 1:] if base else path
        return f"${best}/{relative}"

    def selected(self, path: str) -> tuple[bool, str | None]:
        """(selected, reason-if-excluded-by-a-tree-rule)."""
        if path in self.files:
            return True, None
        if not path.endswith((".java", ".kt")):
            return False, None
        for base, depth, not_names, not_paths in self.trees:
            if not path.startswith(base + "/"):
                continue
            rel = path[len(base) + 1:]
            if depth is not None and rel.count("/") + 1 > depth:
                continue
            name = os.path.basename(path)
            hit = next((pat for pat in not_names if fnmatch.fnmatchcase(name, pat)), None)
            if hit:
                return False, f'excluded by c.add("{self.spec_for(base)}") .not_names "{hit}"'
            hit = next((pat for pat in not_paths if fnmatch.fnmatchcase("/" + path, pat) or fnmatch.fnmatchcase(path, pat)), None)
            if hit:
                return False, f'excluded by c.add("{self.spec_for(base)}") .not_paths "{hit}"'
            return True, None
        return False, None


class Classes:
    """Compiled classes: FQNs of top-level classes from jars/directories."""

    def __init__(self, inputs: list[Path]):
        self.names: set[str] = set()
        for p in inputs:
            if p.is_dir():
                for dirpath, _, filenames in os.walk(p):
                    for f in filenames:
                        if f.endswith(".class"):
                            self.add(os.path.relpath(os.path.join(dirpath, f), p))
            elif p.is_file():
                with zipfile.ZipFile(p) as z:
                    for name in z.namelist():
                        if name.endswith(".class"):
                            self.add(name)
            else:
                sys.exit(f"aosp-closure: classes input does not exist: {p}")
        if not self.names:
            sys.exit("aosp-closure: no classes found; run a build first and pass its framework-classes.jar")
        # The android.annotation markers are compiled in a separate javac pass
        # from the repository runtime; they are present whenever the file is.
        for p in (REPO / "src/annotation-runtime").rglob("*.java"):
            self.names.add(".".join(p.relative_to(REPO / "src/annotation-runtime").with_suffix("").parts))

    def add(self, entry: str) -> None:
        name = entry[:-6].replace("/", ".")
        # Keep both the top-level class and its exact nested-class name.  A
        # source may require Outer.Nested even when a hosted Outer shim is on
        # the class path; collapsing every '$' entry to Outer hid that ABI gap.
        self.names.add(name.replace("$", "."))
        self.names.add(name.split("$", 1)[0])

    def has(self, fqn: str) -> bool:
        if fqn in self.names:
            return True
        return fqn.startswith(BOOT_PREFIXES) and not fqn.startswith(BOOT_PREFIX_EXCEPTIONS)


class Stubs:
    def __init__(self, root: Path, framework_root: Path | None = None):
        self.audit_by_fqn: dict[str, Path] = {}
        self.by_fqn: dict[str, Path] = {}
        self.marker: dict[str, str] = {}
        if framework_root is None:
            framework_root = REPO / "src/framework"
        self.add_root(framework_root, audit=False)
        self.add_root(root, audit=True)

    def add_root(self, root: Path, audit: bool) -> None:
        for p in sorted(root.rglob("*")):
            if p.suffix not in (".java", ".kt") or not p.is_file():
                continue
            text = read(p)
            package = PACKAGE_RE.search(text)
            if package is None:
                continue
            fqn = f"{package.group(1)}.{p.stem}"
            self.by_fqn[fqn] = p
            if audit:
                self.audit_by_fqn[fqn] = p
            head = "\n".join(text.splitlines()[:20])
            m = re.search(r"(artzig[^\n*]*|Hosted adaptation of AOSP[^\n*]*)", head)
            self.marker[fqn] = m.group(1).strip() if m else ""


class Node:
    __slots__ = ("fqn", "kind", "path", "vendored", "selected", "exclusion", "native", "aidl_decl", "aidl_root", "generated", "refs", "referrers", "blockers", "abi_blockers")

    def __init__(self, fqn: str):
        self.fqn = fqn
        self.kind = "missing"  # java | kt | aidl-interface | aidl-parcelable | aidl-structured | generated | missing
        self.path: str | None = None
        self.vendored = False
        self.selected = False
        self.exclusion: str | None = None
        self.native = False
        self.aidl_decl: str | None = None
        self.aidl_root = True
        self.generated: str | None = None
        self.refs: list[str] = []
        self.referrers: set[str] = set()
        self.blockers: list[str] = []
        self.abi_blockers: list[str] = []


class Resolver:
    def __init__(self, aosp: Path, index: SourceIndex, manifest: Manifest, rules: SourceRules, classes: Classes, stubs: Stubs):
        self.aosp, self.index, self.manifest, self.rules, self.classes, self.stubs = aosp, index, manifest, rules, classes, stubs
        self.parsed: dict[str, list[str]] = {}
        self.parsed_abi_blockers: dict[str, list[str]] = {}
        self.source_cache: dict[tuple[str, bool], str] = {}
        self.method_return_cache: dict[tuple[str, str, bool], str | None] = {}
        self.host_method_cache: dict[tuple[str, str], bool] = {}
        self.nodes: dict[str, Node] = {}
        self.absent: set[str] = set()
        # Parcelable .aidl declarations of present stubs that new AIDL interfaces import.
        self.extra_manifest: set[str] = set()
        self.root_packages = {k.split(".", 1)[0] for k in index.by_fqn} | {p.split(".", 1)[0] for p in BOOT_PREFIXES}

    # -- reference extraction -------------------------------------------------
    def refs_of(self, rel_path: str) -> list[str]:
        if rel_path in self.parsed:
            return self.parsed[rel_path]
        text = strip_code(read(self.aosp / rel_path))
        pkg = PACKAGE_RE.search(text)
        pkg = pkg.group(1) if pkg else ""
        current_fqn = self.fqn_of(rel_path)
        explicit: dict[str, str] = {}
        wildcards: list[str] = []
        abi_blockers: set[str] = set()
        static_owners: set[str] = set()
        for m in IMPORT_RE.finditer(text):
            static, name, star = m.group(1), m.group(2), m.group(3)
            if star:
                wildcards.append(name)
                if static:
                    static_owners.add(name)
            elif static:
                owner, member = name.rsplit(".", 1)
                static_owners.add(owner)
                explicit.setdefault(owner.rsplit(".", 1)[-1], owner)
                if (owner != current_fqn and owner in self.stubs.by_fqn
                        and not self.stub_declares(owner, member)):
                    abi_blockers.add(f"existing stub {owner} lacks member {member}")
            else:
                explicit[name.rsplit(".", 1)[-1]] = name
        body = IMPORT_RE.sub(" ", text)
        abi_blockers.update(
            self.method_abi_blockers(body, pkg, current_fqn, explicit, wildcards)
        )
        found: set[str] = set()
        # Package-qualified references are handled below.  Also inspect
        # source-local Outer.Nested references: a compiled Outer stub is not
        # sufficient when it omits the nested type required by stock source.
        for m in SIMPLE_QUALIFIED_RE.finditer(body):
            parts = m.group(1).split(".")
            outer = explicit.get(parts[0], f"{pkg}.{parts[0]}" if pkg else parts[0])
            if outer != current_fqn and outer in self.stubs.by_fqn:
                member = parts[1]
                nested = f"{outer}.{member}"
                if not self.classes.has(nested) and not self.stub_declares(outer, member):
                    kind = "member" if member.isupper() else "nested type"
                    abi_blockers.add(f"existing stub {outer} lacks {kind} {member}")
        for m in QUALIFIED_RE.finditer(body):
            if m.group(1).split(".", 1)[0] in self.root_packages:
                found.add(m.group(1))
        for m in SIMPLE_RE.finditer(body):
            tok = m.group(1)
            if tok in explicit:
                found.add(explicit[tok])
                continue
            for w in wildcards + [pkg]:
                cand = f"{w}.{tok}" if w else tok
                if self.exists(cand):
                    found.add(cand)
                    break
        found.update(explicit.values())
        found.update(static_owners)
        refs = sorted(self.canonical(f) for f in found)
        refs = sorted({r for r in refs if r and r != self.fqn_of(rel_path)})
        self.parsed[rel_path] = refs
        self.parsed_abi_blockers[rel_path] = sorted(abi_blockers)
        return refs

    def stub_declares(self, fqn: str, member: str) -> bool:
        path = self.stubs.by_fqn.get(fqn)
        return bool(path and re.search(rf"\b{re.escape(member)}\b", strip_code(read(path))))

    def host_declares_method(self, fqn: str, member: str) -> bool:
        key = (fqn, member)
        if key in self.host_method_cache:
            return self.host_method_cache[key]
        path = self.stubs.by_fqn.get(fqn)
        if path is None:
            return False
        declared = self.source_declares_method(strip_code(read(path)), member)
        self.host_method_cache[key] = declared
        return declared

    @staticmethod
    def source_declares_method(text: str, member: str) -> bool:
        java = re.search(
            rf"\b(?:public|protected|private|static|final|abstract|synchronized|native|default)"
            rf"\b[^;{{}}=]*\b{re.escape(member)}\s*\(",
            text,
        )
        kotlin = re.search(rf"\bfun\s+(?:<[^>]+>\s*)?{re.escape(member)}\s*\(", text)
        aidl = re.search(
            rf"^\s*(?:@[\w.]+(?:\([^)]*\))?\s+)*(?:oneway\s+)?"
            rf"[\w.$<>?\[\]]+\s+{re.escape(member)}\s*\([^;{{}}]*\)"
            rf"(?:\s+throws\s+[\w., ]+)?\s*(?:=\s*\d+\s*)?;",
            text,
            re.M,
        )
        return bool(java or kotlin or aidl)

    def resolve_source_type(
        self,
        name: str,
        pkg: str,
        explicit: dict[str, str],
        wildcards: list[str],
    ) -> str | None:
        name = re.sub(r"<.*>", "", name).replace("[]", "").strip()
        name = re.sub(r"^@[\w.]+(?:\([^)]*\))?\s*", "", name)
        if name in {"boolean", "byte", "char", "double", "float", "int", "long", "short", "void"}:
            return name
        if "." in name:
            return self.canonical(name)
        if name in explicit:
            return self.canonical(explicit[name])
        for prefix in [pkg, *wildcards]:
            candidate = f"{prefix}.{name}" if prefix else name
            if self.exists(candidate):
                return self.canonical(candidate)
        return None

    def source_for(self, fqn: str, host_first: bool = True) -> str:
        key = (fqn, host_first)
        if key in self.source_cache:
            return self.source_cache[key]
        host = self.stubs.by_fqn.get(fqn) if host_first else None
        if host is not None:
            source = read(host)
        else:
            sources = self.index.lookup(fqn)
            paths = sources.get("java") or sources.get("kt") or sources.get("aidl") or []
            source = read(self.aosp / self.pick(paths)) if paths else ""
        self.source_cache[key] = source
        return source

    def method_return_type(
        self,
        fqn: str,
        member: str,
        host_first: bool = True,
    ) -> str | None:
        key = (fqn, member, host_first)
        if key in self.method_return_cache:
            return self.method_return_cache[key]
        text = strip_code(self.source_for(fqn, host_first=host_first))
        package = PACKAGE_RE.search(text)
        pkg = package.group(1) if package else fqn.rpartition(".")[0]
        explicit: dict[str, str] = {}
        wildcards: list[str] = []
        for imported in IMPORT_RE.finditer(text):
            if imported.group(1):
                continue
            if imported.group(3):
                wildcards.append(imported.group(2))
            else:
                name = imported.group(2)
                explicit[name.rsplit(".", 1)[-1]] = name
        # Framework Java methods in the closure are public/protected. Keeping
        # this declaration-shaped avoids mistaking an invocation for a method.
        java = re.search(
            rf"\b(?:public|protected)\s+"
            rf"(?:(?:static|final|synchronized|native|abstract|default)\s+)*"
            rf"(?:@[\w.]+(?:\([^)]*\))?\s+)*"
            rf"(?P<type>[\w.$<>?\[\]]+)\s+{re.escape(member)}\s*\(",
            text,
        )
        if java:
            result = self.resolve_source_type(java.group("type"), pkg, explicit, wildcards)
            self.method_return_cache[key] = result
            return result
        aidl = re.search(
            rf"^\s*(?:@[\w.]+(?:\([^)]*\))?\s+)*(?:oneway\s+)?"
            rf"(?P<type>[\w.$<>?\[\]]+)\s+{re.escape(member)}\s*\(",
            text,
            re.M,
        )
        if aidl:
            result = self.resolve_source_type(aidl.group("type"), pkg, explicit, wildcards)
            self.method_return_cache[key] = result
            return result
        kotlin = re.search(
            rf"\bfun\s+(?:<[^>]+>\s*)?{re.escape(member)}\s*\([^)]*\)\s*:\s*"
            rf"(?P<type>[\w.$<>?\[\]]+)",
            text,
        )
        if kotlin:
            result = self.resolve_source_type(kotlin.group("type"), pkg, explicit, wildcards)
            self.method_return_cache[key] = result
            return result
        self.method_return_cache[key] = None
        return None

    def method_abi_blockers(
        self,
        text: str,
        pkg: str,
        current_fqn: str,
        explicit: dict[str, str],
        wildcards: list[str],
    ) -> set[str]:
        blockers: set[str] = set()

        def check(owner: str | None, member: str) -> None:
            if not owner or owner == current_fqn or owner not in self.stubs.by_fqn:
                return
            stock_source = strip_code(self.source_for(owner, host_first=False))
            # A method absent from the stock owner's own source may be inherited
            # (notably Object.getClass); the host inherits it too and is not an
            # ABI blocker merely because its replacement file omits the token.
            if not self.source_declares_method(stock_source, member):
                return
            if not self.host_declares_method(owner, member):
                blockers.add(f"existing host class {owner} lacks method {member}")
                return
            host_return = self.method_return_type(owner, member)
            stock_return = self.method_return_type(owner, member, host_first=False)
            # Covariant reference returns are valid. Primitive and void returns
            # are exact ABI, and a mismatch otherwise fails javac at the call.
            primitives = {"boolean", "byte", "char", "double", "float", "int", "long", "short", "void"}
            if (host_return is not None and stock_return is not None
                    and (host_return in primitives or stock_return in primitives)
                    and host_return != stock_return):
                blockers.add(
                    f"existing host class {owner} method {member} returns "
                    f"{host_return or 'unknown'}, stock requires {stock_return or 'unknown'}"
                )

        variables: dict[str, str] = {}
        for declared in re.finditer(
            r"\b(?:final\s+)?(?P<type>[A-Z][\w.$]*(?:<[^;={}]+>)?(?:\[\])?)\s+"
            r"(?P<name>[a-z_]\w*)\s*(?:=|;)",
            text,
        ):
            resolved = self.resolve_source_type(
                declared.group("type"), pkg, explicit, wildcards,
            )
            if resolved:
                variables[declared.group("name")] = resolved

        # Direct static calls, for example WindowManagerImpl.createFoo(...).
        for call in re.finditer(r"\b(?P<owner>[A-Z]\w*)\s*\.\s*(?P<member>[a-zA-Z_]\w*)\s*\(", text):
            owner = self.resolve_source_type(call.group("owner"), pkg, explicit, wildcards)
            check(owner, call.group("member"))

        # Calls through a typed local or field.
        for call in re.finditer(r"\b(?P<owner>[a-z_]\w*)\s*\.\s*(?P<member>[a-zA-Z_]\w*)\s*\(", text):
            check(variables.get(call.group("owner")), call.group("member"))

        # One return-value hop catches the common framework service pattern:
        # WindowManagerGlobal.getWindowManagerService().someBinderCall(...),
        # and unqualified local helpers such as getController().attach(...).
        chained = re.compile(
            r"\b(?:(?P<owner>[A-Z]\w*)\s*\.\s*)?"
            r"(?P<first>[a-zA-Z_]\w*)\s*\([^()]*\)\s*\.\s*"
            r"(?P<second>[a-zA-Z_]\w*)\s*\("
        )
        for call in chained.finditer(text):
            owner_name = call.group("owner")
            owner = (
                self.resolve_source_type(owner_name, pkg, explicit, wildcards)
                if owner_name else current_fqn
            )
            returned = self.method_return_type(owner, call.group("first")) if owner else None
            check(returned, call.group("second"))

        # Replacing an abstract host superclass can also invalidate a concrete
        # repo-owned subclass even when the new class's own body type-checks.
        abstract_methods = set(re.findall(
            r"\babstract\s+(?:@[\w.]+(?:\([^)]*\))?\s+)*"
            r"[\w.$<>?\[\]]+\s+([a-zA-Z_]\w*)\s*\(",
            text,
        ))
        current_simple = current_fqn.rsplit(".", 1)[-1]
        is_abstract_class = bool(re.search(
            rf"\babstract\s+class\s+{re.escape(current_simple)}\b", text,
        ))
        if abstract_methods or is_abstract_class:
            for subclass, path in self.stubs.by_fqn.items():
                if subclass == current_fqn:
                    continue
                subclass_text = strip_code(read(path))
                if is_abstract_class:
                    subclass_package_match = PACKAGE_RE.search(subclass_text)
                    subclass_package = (
                        subclass_package_match.group(1) if subclass_package_match else ""
                    )
                    imported = {
                        match.group(2).rsplit(".", 1)[-1]: match.group(2)
                        for match in IMPORT_RE.finditer(subclass_text)
                        if not match.group(1) and not match.group(3)
                    }
                    for instantiated in re.finditer(r"\bnew\s+([\w.]+)\s*\(", subclass_text):
                        name = instantiated.group(1)
                        resolved = (
                            name if "." in name
                            else imported.get(name, f"{subclass_package}.{name}")
                        )
                        if resolved == current_fqn:
                            blockers.add(
                                f"existing host class {subclass} instantiates abstract class {current_fqn}"
                            )
                declaration = re.search(
                    r"(?P<mods>(?:(?:public|protected|private|abstract|final)\s+)*)"
                    r"class\s+\w+\s+extends\s+(?P<base>[\w.]+)",
                    subclass_text,
                )
                if not declaration or "abstract" in declaration.group("mods").split():
                    continue
                base = declaration.group("base")
                subclass_pkg = subclass.rpartition(".")[0]
                if base not in (current_simple, current_fqn, f"{subclass_pkg}.{current_simple}"):
                    continue
                for member in abstract_methods:
                    if not self.host_declares_method(subclass, member):
                        blockers.add(
                            f"existing host class {subclass} does not implement abstract method {member}"
                        )
        return blockers

    def fqn_of(self, rel_path: str) -> str:
        text = read(self.aosp / rel_path)
        m = PACKAGE_RE.search(text)
        name = os.path.splitext(os.path.basename(rel_path))[0]
        return f"{m.group(1)}.{name}" if m else name

    def exists(self, fqn: str) -> bool:
        if self.classes.has(fqn) or bool(self.index.lookup(fqn)) or fqn in self.stubs.by_fqn or fqn in KNOWN_GENERATED:
            return True
        pkg, _, name = fqn.rpartition(".")
        return name in ACONFIG_CLASSES and pkg in self.index.aconfig

    def canonical(self, fqn: str) -> str:
        """Reduce nested references (a.b.C.D, a.b.C.CONST) to the top-level class."""
        parts = fqn.split(".")
        first_class = next((i for i, part in enumerate(parts) if part[:1].isupper()), None)
        if first_class is not None and first_class + 1 < len(parts):
            suffix = parts[-1]
            # A missing nested type must not be collapsed to a present outer
            # shim. Constants and member names still resolve through Outer.
            if suffix[:1].isupper() and not suffix.isupper() and not self.exists(fqn):
                return fqn
        for i in range(len(parts), 0, -1):
            cand = ".".join(parts[:i])
            if not parts[i - 1][:1].isupper():
                break
            if self.exists(cand):
                return cand
        # Unknown qualified name: keep the first capitalized segment as the class.
        for i, p in enumerate(parts):
            if p[:1].isupper():
                return ".".join(parts[: i + 1])
        return fqn

    # -- node construction ----------------------------------------------------
    def node(self, fqn: str) -> Node:
        if fqn in self.nodes:
            return self.nodes[fqn]
        n = Node(fqn)
        self.nodes[fqn] = n
        srcs = self.index.lookup(fqn)
        if not srcs:
            # Nested types live in their outer class's source file.  Resolve a
            # missing nested ABI requirement to that file so the closure asks
            # for the stock outer class instead of reporting "no source".
            parts = fqn.split(".")
            first_class = next((i for i, part in enumerate(parts) if part[:1].isupper()), None)
            if first_class is not None and first_class + 1 < len(parts):
                srcs = self.index.lookup(".".join(parts[: first_class + 1]))
        path = None
        if srcs.get("java"):
            path, n.kind = self.pick(srcs["java"]), "java"
        elif srcs.get("kt"):
            path, n.kind = self.pick(srcs["kt"]), "kt"
        elif srcs.get("aidl"):
            path = self.pick(srcs["aidl"])
            # Legacy interfaces may declare imported parcelables before their
            # own interface (IBluetooth does). Classify the file's declaration,
            # not the first forward declaration it happens to contain.
            decl = next((declaration for declaration in
                         AIDL_DECL_RE.finditer(strip_code(read(self.aosp / path)))
                         if declaration.group(2) == Path(path).stem), None)
            if decl and decl.group(1) == "interface":
                n.kind = "aidl-interface"
            elif decl and decl.group(3) == "{":
                n.kind = "aidl-structured"
            else:
                n.kind = "aidl-parcelable"
            n.aidl_decl = decl.group(1) if decl else None
            n.aidl_root = path in STAGED_AIDL or any(path.startswith(r + "/") for r in AIDL_ROOTS)
        elif srcs.get("logtags"):
            n.kind, n.generated = "generated", "logtags generator (build/generator_sources.zig)"
        elif srcs.get("proto"):
            n.kind, n.generated = "generated", "proto generator (build/generator_sources.zig)"
        else:
            pkg, _, name = fqn.rpartition(".")
            if name in ACONFIG_CLASSES and pkg in self.index.aconfig:
                n.kind, n.generated = "aconfig", pkg
            elif fqn in KNOWN_GENERATED:
                n.kind, n.generated = "generated", KNOWN_GENERATED[fqn]
            elif name.endswith("Proto") or name == "EventLogTags" or name == "FrameworkStatsLog":
                n.kind, n.generated = "generated", "proto/logtags/stats generator (build/generator_sources.zig)"
            elif pkg == "android.sysprop":
                n.kind, n.generated = "generated", "sysprop accessor (build/generator_sources.zig)"
        if path:
            n.path = path
            n.vendored = self.manifest.vendored(path)
            n.selected, n.exclusion = self.rules.selected(path)
            text = strip_code(read(self.aosp / path))
            if n.kind in ("java", "kt"):
                n.native = bool(NATIVE_RE.search(text))
                n.refs = self.refs_of(path)
                n.abi_blockers = [
                    blocker for blocker in self.parsed_abi_blockers.get(path, [])
                    if self.abi_blocker_owner(blocker) not in self.absent
                ]
            elif n.kind == "aidl-interface" or n.kind == "aidl-structured":
                n.refs = self.aidl_refs(path, text)
            elif n.kind == "aidl-parcelable":
                # Declaration only: the Java class is the same FQN (already handled
                # by the java lookup above when it exists); nothing more to add.
                pass
        return n

    def pick(self, paths: list[str]) -> str:
        """Prefer a vendored path, then the shortest (frameworks/base first)."""
        return sorted(paths, key=lambda p: (not self.manifest.vendored(p), not p.startswith("frameworks/base/"), len(p)))[0]

    @staticmethod
    def abi_blocker_owner(blocker: str) -> str | None:
        match = re.match(r"existing (?:stub|host class) ([\w.]+) ", blocker)
        return match.group(1) if match else None

    def aidl_refs(self, rel_path: str, text: str) -> list[str]:
        pkg = PACKAGE_RE.search(text)
        pkg = pkg.group(1) if pkg else ""
        found: set[str] = set()
        for m in IMPORT_RE.finditer(text):
            found.add(m.group(2))
        body = IMPORT_RE.sub(" ", text)
        for m in QUALIFIED_RE.finditer(body):
            if m.group(1).split(".", 1)[0] in self.root_packages:
                found.add(m.group(1))
        for m in SIMPLE_RE.finditer(body):
            tok = m.group(1)
            cand = f"{pkg}.{tok}"
            if self.exists(cand):
                found.add(cand)
        return sorted({self.canonical(f) for f in found} - {self.fqn_of(rel_path)})

    # -- closure --------------------------------------------------------------
    def closure(self, seeds: list[str], absent: set[str] = frozenset()) -> dict[str, Node]:
        """Nodes that must be added so every seed compiles; present classes stop the walk."""
        self.absent = set(absent)
        result: dict[str, Node] = {}
        queue = list(seeds)
        seen: set[str] = set()
        self.parent: dict[str, str] = {}
        while queue:
            fqn = queue.pop(0)  # breadth first: parent chains are shortest paths
            if fqn in seen:
                continue
            seen.add(fqn)
            n = self.node(fqn)
            result[fqn] = n
            for ref in n.refs:
                # An AIDL interface importing a class that is already compiled (a
                # stub or a real class) still needs that class's parcelable
                # declaration in the package for the aidl compiler.
                if n.kind.startswith("aidl") and ref not in absent and self.classes.has(ref):
                    for a in self.index.lookup(ref).get("aidl", []):
                        if not self.manifest.vendored(a):
                            self.extra_manifest.add(a)
                if ref in absent or not self.classes.has(ref):
                    if ref in self.stubs.by_fqn and ref not in absent:
                        continue
                    self.node(ref).referrers.add(fqn)
                    self.parent.setdefault(ref, fqn)
                    queue.append(ref)
            # A Parcelable's sibling .aidl declaration must ship for AIDL imports.
            if n.kind in ("java", "kt") and n.path:
                srcs = self.index.lookup(fqn)
                for a in srcs.get("aidl", []):
                    if not self.manifest.vendored(a):
                        n.blockers.append(f"sibling declaration {a} not in manifest")
        return result

    def chain(self, fqn: str, stop: str) -> str:
        """seed > ... > fqn along the breadth-first parents (short class names)."""
        names = [fqn]
        while fqn in self.parent and fqn != stop and len(names) < 8:
            fqn = self.parent[fqn]
            names.append(fqn)
        return " < ".join(n.rsplit(".", 1)[-1] for n in names)

    def present_stubs(self, seeds: list[str]) -> set[str]:
        """Stubs the seeds' sources reference (they stay as they are)."""
        out: set[str] = set()
        for fqn in seeds:
            for ref in self.node(fqn).refs:
                if ref in self.stubs.by_fqn:
                    out.add(ref)
        return out


def blockers_of(n: Node) -> list[str]:
    b: list[str] = list(n.abi_blockers)
    if n.kind == "missing":
        b.append("no source in the checkout")
    elif n.kind == "aconfig":
        pass  # addable: a generator_sources.zig aconfig entry (+ manifest lines for the declarations)
    elif n.kind == "generated":
        b.append(f"generated: {n.generated}")
    else:
        if n.native:
            b.append("JNI natives")
        if n.kind.startswith("aidl") and not n.aidl_root:
            b.append("AIDL outside the configured include roots")
    return b


def render_closure(res: Resolver, seeds: list[str], nodes: dict[str, Node]) -> str:
    out: list[str] = []
    present = lambda n: res.classes.has(n.fqn) and n.fqn not in seeds  # noqa: E731
    add_java = [n for n in nodes.values() if n.kind in ("java", "kt") and not present(n)]
    add_aidl = [n for n in nodes.values() if n.kind.startswith("aidl") and not present(n)]
    blocked = [n for n in nodes.values() if blockers_of(n)]
    out.append(f"== closure of {', '.join(seeds)}: {len(add_java)} source(s), {len(add_aidl)} AIDL, {len(blocked)} blocker(s)")
    stubs_seen = sorted(s for s in res.present_stubs(seeds))
    if stubs_seen:
        out.append("existing host replacements referenced (count as present): " + ", ".join(stubs_seen))
    for n in sorted(nodes.values(), key=lambda n: n.fqn):
        if present(n):
            continue
        flags = []
        if n.path and not n.vendored:
            flags.append("NOT VENDORED")
        if n.exclusion:
            flags.append(n.exclusion)
        flags.extend(blockers_of(n))
        via = f"  <- {', '.join(sorted(n.referrers)[:3])}" if n.referrers else ""
        out.append(f"  {n.kind:16} {n.fqn}  [{n.path or '-'}]{'  ' + '; '.join(flags) if flags else ''}{via}")

    manifest_lines: set[str] = set()
    source_lines: set[str] = set()
    aidl_lines: set[str] = set()
    for n in nodes.values():
        if present(n) or not n.path:
            continue
        if not n.vendored:
            manifest_lines.add(f"F aosp {n.path}")
        if n.kind in ("java", "kt"):
            # An exclusion means the surrounding c.add tree does not select
            # this file.  It still needs an explicit c.file entry; suppressing
            # that line made the reported closure incomplete for patterns such
            # as DatePicker*.java and android/window/*.java.
            if not n.selected:
                source_lines.add(f'    try c.file("{res.rules.spec_for(n.path)}");')
            for a in res.index.lookup(n.fqn).get("aidl", []):
                if not res.manifest.vendored(a):
                    manifest_lines.add(f"F aosp {a}")
        elif n.kind in ("aidl-interface", "aidl-structured"):
            aidl_lines.add(f'    .{{ .source = .aosp, .path = "{n.path}" }},')
    for a in res.extra_manifest:
        manifest_lines.add(f"F aosp {a}")
    logtags_lines: set[str] = set()
    proto_inputs: set[str] = set()
    proto_outputs: set[str] = set()
    for n in nodes.values():
        if not present(n):
            for path in res.index.lookup(n.fqn).get("proto", []):
                if not res.manifest.vendored(path):
                    manifest_lines.add(f"F aosp {path}")
                proto_inputs.add(f'    .{{ .source = .aosp, .path = "{path}" }},')
                proto_outputs.add(f'    "{n.fqn.replace(".", "/")}.java",')
        if present(n):
            continue
        for path in res.index.lookup(n.fqn).get("logtags", []):
            if not res.manifest.vendored(path):
                manifest_lines.add(f"F aosp {path}")
            output = n.fqn.replace(".", "/") + ".java"
            logtags_lines.add(
                f'    .{{ .input = .{{ .source = .aosp, .path = "{path}" }},'
                f' .output = "{output}" }},')
    aconfig_lines: set[str] = set()
    for n in nodes.values():
        if n.kind == "aconfig" and not present(n):
            decls = res.index.aconfig[n.generated]
            declarations = ", ".join(f'"{d}"' for d in decls)
            containers = {m.group(1) for d in decls
                          if (m := re.search(r'^\s*container:\s*"([\w.]+)"', read(res.aosp / d), re.M))}
            if len(containers) > 1:
                raise ValueError(f"conflicting aconfig containers for {n.generated}: {containers}")
            container = next(iter(containers), "system")
            aconfig_lines.add(
                f'    .{{ .package = "{n.generated}", .container = "{container}", .source = .aosp,'
                f" .declarations = &.{{{declarations}}} }},"
            )
            for d in decls:
                if not res.manifest.vendored(d):
                    manifest_lines.add(f"F aosp {d}")
    if manifest_lines:
        out.append("== aosp/androlinzberg-files.txt")
        out.extend(sorted(manifest_lines))
    if source_lines:
        out.append("== build/java_sources.zig")
        out.extend(sorted(source_lines))
    if aidl_lines:
        out.append("== build/generator_sources.zig (aidl)")
        out.extend(sorted(aidl_lines))
    if logtags_lines:
        out.append("== build/generator_sources.zig (logtags)")
        out.extend(sorted(logtags_lines))
    if proto_inputs:
        out.append("== build/generator_sources.zig (proto_inputs; select the module's proto backend)")
        out.extend(sorted(proto_inputs))
        out.append("== build/generator_sources.zig (proto_outputs)")
        out.extend(sorted(proto_outputs))
    if aconfig_lines:
        out.append("== build/generator_sources.zig (aconfig)")
        out.extend(sorted(aconfig_lines))
    return "\n".join(out)


def classify_stub(res: Resolver, fqn: str) -> tuple[str, str, dict[str, Node] | None]:
    """(status, detail, closure) for one stub evaluated as if it were removed."""
    srcs = res.index.lookup(fqn)
    if not srcs.get("java") and not srcs.get("kt") and not srcs.get("aidl"):
        for kind in ("proto", "logtags"):
            if srcs.get(kind):
                return "generated", f"{kind} declaration ({', '.join(srcs[kind])})", None
        pkg, _, name = fqn.rpartition(".")
        if name in ACONFIG_CLASSES and pkg in res.index.aconfig:
            return "generated", f"aconfig package {pkg} ({', '.join(res.index.aconfig[pkg])})", None
        return "no-aosp-source", "no class with this name in the checkout", None
    # Evaluate the real class with the stub itself absent from the class set.
    saved = res.classes.names
    res.classes.names = saved - {fqn}
    res.nodes = {}
    try:
        nodes = res.closure([fqn], absent={fqn})
    finally:
        res.classes.names = saved
    seed = nodes[fqn]
    blockers: list[str] = []
    if seed.kind.startswith("aidl"):
        blockers.extend(blockers_of(seed))
    if seed.native:
        blockers.append("real class has JNI natives")
    for n in nodes.values():
        for b in blockers_of(n):
            if n is seed and b == "JNI natives":
                continue
            blockers.append(f"{n.fqn}: {b} (via {res.chain(n.fqn, fqn)})")
    n_add = sum(1 for n in nodes.values() if not res.classes.has(n.fqn) or n.fqn == fqn)
    detail = f"{seed.path} ({n_add} to add{', AIDL interface' if seed.kind.startswith('aidl') else ''})"
    if not seed.vendored:
        detail += ", not vendored"
    if seed.exclusion:
        detail += f", {seed.exclusion}"
    if blockers:
        return "blocked", detail + "; " + "; ".join(sorted(set(blockers))[:6]), nodes
    return "replaceable", detail, nodes


def cmd_closure(args: argparse.Namespace, res: Resolver) -> int:
    seeds = []
    for s in args.seeds:
        if s.endswith((".java", ".kt", ".aidl")):
            seeds.append(res.fqn_of(s))
        else:
            seeds.append(s)
    res.classes.names |= set(args.assume_present)
    nodes = res.closure(seeds, absent=set(seeds))
    print(render_closure(res, seeds, nodes))
    for fqn in args.explain:
        if fqn not in nodes:
            print(f"== {fqn}: not in the closure")
            continue
        chain = [fqn]
        while chain[-1] in res.parent and chain[-1] not in seeds and len(chain) < 40:
            chain.append(res.parent[chain[-1]])
        print(f"== {fqn}: " + " <- ".join(chain))
    return 1 if any(blockers_of(n) for n in nodes.values()) else 0


AUDIT_HEADER = """# Stub audit: generated by `tools/aosp-closure.py audit --update tools/stub-audit.txt`
# from a live classes jar; the family column is curated by hand and preserved
# across regeneration. Fields: stub path|audit status|family|detail.
#   status  replaceable      the real class compiles once the listed sources are added
#           blocked          the real closure reaches a JNI class, an unvendored module,
#                            an AIDL/generator gap, or a member absent from a host replacement
#           no-aosp-source   no class with this name in the checkout (host-only or module not synced)
#           generated        the class is produced by a generator (aconfig/proto/...)
#   family  a manager family this milestone replaces (notification, alarm, ...), another
#           area (ui, window, ...), or `survivor: <reason>` for a stub that stays.
# The jvm-source build audit rejects a vendored-duplicate stub that is not listed here and
# fails when more than `pending-budget` entries are not survivors; lower the budget as
# stubs are replaced, never raise it.
"""


def read_audit(path: Path) -> tuple[dict[str, tuple[str, str]], int | None]:
    families: dict[str, tuple[str, str]] = {}
    budget = None
    for line in read(path).splitlines():
        if line.startswith("# pending-budget:"):
            budget = int(line.split(":", 1)[1].strip())
            continue
        if not line or line.startswith("#"):
            continue
        parts = line.split("|", 3)
        if len(parts) >= 3:
            families[parts[0]] = (parts[2], parts[3] if len(parts) > 3 else "")
    return families, budget


def hub_analysis(res: Resolver, closures: dict[str, dict[str, Node]]) -> list[tuple[str, int]]:
    """Intermediate classes on blocker chains, ranked by how many stubs they block."""
    counts: dict[str, set[str]] = defaultdict(set)
    hops: dict[str, int] = {}
    for stub, nodes in closures.items():
        # Re-run the closure to recover the parent chains of this stub.
        saved = res.classes.names
        res.classes.names = saved - {stub}
        res.nodes = {}
        try:
            nodes = res.closure([stub], absent={stub})
        finally:
            res.classes.names = saved
        for n in nodes.values():
            if not blockers_of(n) or n.fqn == stub:
                continue
            f = n.fqn
            chain = []
            while f in res.parent and res.parent[f] != stub:
                f = res.parent[f]
                chain.append(f)
            for i, f in enumerate(reversed(chain)):
                counts[f].add(stub)
                hops[f] = min(hops.get(f, 99), i + 1)
    return sorted(((k, len(v), hops[k]) for k, v in counts.items()), key=lambda kv: (-kv[1], kv[2], kv[0]))


def write_markdown(path: Path, rows: list, hubs: list[tuple[str, int]], budget: int) -> None:
    survivors = [r for r in rows if r[3].startswith("survivor")]
    pending = [r for r in rows if not r[3].startswith("survivor")]
    out = ["# Framework stubs", "",
           "Generated by `tools/aosp-closure.py audit --update tools/stub-audit.txt --markdown docs/stubs.md`",
           "from a live build; do not edit by hand. A stub under `src/framework-stubs` replaces an",
           "AOSP class the curated build does not compile. Every stub is either a **survivor** with",
           "the reason the real class cannot be compiled on this host, or **pending** replacement by",
           "the real AOSP class in the family's milestone phase. The audit status is what the",
           "closure tool sees today: `replaceable` means the real class compiles once the sources",
           "the tool lists are added; `blocked` names the first classes of the real closure that",
           "need a host seam (JNI, an unvendored module tree, an AIDL/generator gap, or a",
           "member absent from a host replacement).", "",
           f"Pending: {len(pending)} (budget {budget}). Survivors: {len(survivors)}. Total: {len(rows)}.", "",
           "## Survivors", "", "| Stub | Reason | Audit |", "|---|---|---|"]
    for p, fqn, status, family, detail in survivors:
        out.append(f"| `{p.removeprefix('src/framework-stubs/')}` | {family.removeprefix('survivor:').strip()} | {status} |")
    out += ["", "## Pending replacement", ""]
    by_family: dict[str, list] = defaultdict(list)
    for r in pending:
        by_family[r[3] or "unassigned"].append(r)
    for family in sorted(by_family):
        out += [f"### {family}", "", "| Stub | Audit | Closure |", "|---|---|---|"]
        for p, fqn, status, _, detail in by_family[family]:
            d = detail.replace("|", "/")
            out.append(f"| `{p.removeprefix('src/framework-stubs/')}` | {status} | {d[:300]} |")
        out.append("")
    out += ["## Hubs", "",
            "Intermediate classes through which the real closures reach a blocker, ranked by the",
            "number of stubs they block. A marked host stub at a hub (or an exclusion of the",
            "hub's reference) unblocks every stub behind it; the phase that owns the family",
            "decides where to cut.", "", "| Class | Stubs blocked through it | Hops from the nearest stub |", "|---|---|---|"]
    for cls, n, h in hubs[:40]:
        out.append(f"| `{cls}` | {n} | {h} |")
    out.append("")
    path.write_text("\n".join(out))


def cmd_audit(args: argparse.Namespace, res: Resolver) -> int:
    families, budget = read_audit(args.update) if args.update else ({}, None)
    rows = []
    blocked_closures: dict[str, dict[str, Node]] = {}
    for fqn, path in sorted(res.stubs.audit_by_fqn.items()):
        status, detail, nodes = classify_stub(res, fqn)
        rel = str(path.relative_to(REPO))
        family = families.get(rel, ("", ""))[0]
        rows.append((rel, fqn, status, family, detail))
        if status == "blocked" and nodes is not None:
            blocked_closures[fqn] = nodes
    hubs = hub_analysis(res, blocked_closures) if (args.markdown or args.hubs) else []
    counts = defaultdict(int)
    for r in rows:
        counts[r[2]] += 1
    pending = sum(1 for r in rows if not r[3].startswith("survivor"))
    if args.json:
        print(json.dumps([dict(zip(("path", "fqn", "status", "family", "detail"), r)) for r in rows], indent=1))
    elif not args.update:
        for rel, fqn, status, family, detail in rows:
            print(f"{status:16} {rel}  {detail}")
        print("== " + ", ".join(f"{k}={v}" for k, v in sorted(counts.items())))
    if args.hubs:
        print("== hubs (stubs blocked through the class)")
        for cls, n, h in hubs[:40]:
            print(f"{n:4} {h:3} {cls}")
    if args.update:
        if budget is None:
            budget = pending
        lines = [AUDIT_HEADER, f"# pending-budget: {budget}", ""]
        for rel, fqn, status, family, detail in rows:
            lines.append(f"{rel}|{status}|{family}|{detail.replace('|', '/')}")
        args.update.write_text("\n".join(lines) + "\n")
        unassigned = [r[0] for r in rows if not r[3]]
        print(f"{args.update}: {len(rows)} stubs, {pending} pending (budget {budget}), "
              + ", ".join(f"{k}={v}" for k, v in sorted(counts.items()))
              + (f"; {len(unassigned)} without a family" if unassigned else ""))
        for u in unassigned:
            print(f"  unassigned: {u}")
    if args.markdown:
        write_markdown(args.markdown, rows, hubs, budget if budget is not None else pending)
        print(f"{args.markdown}: written")
    return 0


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--classes", action="append", type=Path, required=True, help="framework-classes.jar or a classes directory (repeatable)")
    ap.add_argument("--aosp", type=Path, default=REPO / "aosp", help="AOSP checkout root (default: aosp/)")
    ap.add_argument("--manifest", type=Path, default=REPO / "aosp/androlinzberg-files.txt")
    ap.add_argument("--sources", type=Path, default=REPO / "build/java_sources.zig")
    ap.add_argument("--stubs", type=Path, default=REPO / "src/framework-stubs")
    ap.add_argument("--no-cache", action="store_true", help="rebuild the checkout index")
    sub = ap.add_subparsers(dest="command", required=True)
    c = sub.add_parser("closure", help="what has to be added so the seeds compile")
    c.add_argument("--assume-present", action="append", default=[], metavar="FQN",
                   help="treat this class as compiled (a planned host stub or cut); repeatable")
    c.add_argument("--explain", action="append", default=[], metavar="FQN",
                   help="print the reference chain from a seed to this class; repeatable")
    c.add_argument("seeds", nargs="+")
    a = sub.add_parser("audit", help="classify every stub as replaceable/blocked/no-aosp-source")
    a.add_argument("--json", action="store_true")
    a.add_argument("--hubs", action="store_true", help="rank the intermediate classes that carry blockers")
    a.add_argument("--update", type=Path, help="rewrite this audit list (tools/stub-audit.txt), keeping its family column")
    a.add_argument("--markdown", type=Path, help="write the human-readable report (docs/stubs.md)")
    args = ap.parse_args(argv)

    if not (args.aosp / "frameworks/base").is_dir():
        sys.exit(f"aosp-closure: {args.aosp} is not an AOSP checkout (frameworks/base missing)")
    cache = None if args.no_cache else REPO / ".cache" / "aosp-closure-index.json"
    classes = Classes(args.classes)
    index = SourceIndex(args.aosp, cache)
    res = Resolver(args.aosp, index, Manifest(args.manifest), SourceRules(args.sources), classes, Stubs(args.stubs))
    if args.command == "closure":
        return cmd_closure(args, res)
    return cmd_audit(args, res)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
