#!/usr/bin/env python3
"""Generate an unsupported-by-default Bn base from a generated AIDL C++ header.

The C++ AIDL backend emits ``IFooDefault`` with every method returning
``UNKNOWN_TRANSACTION``; that class is not a Binder object.  This tool mirrors
its method set onto ``BnFooUnsupported : public BnFoo`` where every method is
virtual and returns ``EX_UNSUPPORTED_OPERATION``, so a host service overrides
only the operations it serves and the rest fail the way an absent Android
feature does.  Usage: gen-unsupported-cpp.py <IFoo.h> <output-dir>
"""
import pathlib
import re
import sys


def main() -> int:
    header = pathlib.Path(sys.argv[1])
    out_dir = pathlib.Path(sys.argv[2])
    text = header.read_text()
    match = re.search(r"class (?:LIBBINDER_EXPORTED )?(\w+)Default : public \1 \{(.*?)\n\};", text, re.S)
    if match is None:
        sys.exit(f"{header}: no Default class")
    name = match.group(1)
    body = match.group(2)
    methods = re.findall(r"\n  ::android::binder::Status (\w+)\((.*?)\) override \{", body, re.S)
    namespace = re.findall(r"^namespace (\w+) \{", text, re.M)
    params_out = []
    for method, params in methods:
        # Restore the commented-out parameter names so overriders can copy the signature.
        params_out.append((method, re.sub(r"/\*(\w+)\*/", r"\1", params)))
    lines = [
        "// Generated by tools/gen-unsupported-cpp.py from %s; do not edit." % header.name,
        "#pragma once",
        "#include <android/media/Bn%s.h>" % name[1:],
        "",
    ]
    lines += ["namespace %s {" % n for n in namespace]
    lines.append("")
    lines.append("class Bn%sUnsupported : public Bn%s {" % (name[1:], name[1:]))
    lines.append("public:")
    for method, params in params_out:
        lines.append("  ::android::binder::Status %s(%s) override {" % (method, params))
        lines.append("    return ::android::binder::Status::fromExceptionCode(::android::binder::Status::EX_UNSUPPORTED_OPERATION, \"%s.%s\");" % (name, method))
        lines.append("  }")
    lines.append("};")
    lines.append("")
    lines += ["}  // namespace %s" % n for n in reversed(namespace)]
    lines.append("")
    target = out_dir / "azk" / "audio" / ("Bn%sUnsupported.h" % name[1:])
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
