package dev.artzig.tools

import com.google.common.hash.Hashing
import java.nio.charset.StandardCharsets
import java.nio.file.Files
import java.nio.file.Path
import kotlin.io.path.extension

private data class Metric(val id: String, val type: Int)

private fun readCatalog(directory: Path): List<Metric> {
    val metrics = linkedMapOf<String, Metric>()
    Files.list(directory).use { paths ->
        paths.filter { Files.isRegularFile(it) && it.extension == "cfg" }
            .sorted()
            .forEach { path ->
                var depth = 0
                var id: String? = null
                var type: Int? = null
                Files.readAllLines(path).forEach { rawLine ->
                    val line = rawLine.trim()
                    if (depth == 0) {
                        if (line == "express_metric {") depth = 1
                        return@forEach
                    }
                    if (depth == 1) {
                        if (line.startsWith("id:")) {
                            id = line.substringAfter(':').trim().removeSurrounding("\"")
                        } else if (line.startsWith("type:")) {
                            type = when (line.substringAfter(':').trim()) {
                                "COUNTER" -> 1
                                "HISTOGRAM" -> 2
                                "COUNTER_WITH_UID" -> 3
                                "HISTOGRAM_WITH_UID" -> 4
                                else -> error("unknown metric type in $path: $line")
                            }
                        }
                    }
                    depth += line.count { it == '{' } - line.count { it == '}' }
                    if (depth == 0) {
                        val metric = Metric(
                            id ?: error("metric without id in $path"),
                            type ?: error("metric without type in $path"),
                        )
                        check(metrics.put(metric.id, metric) == null) {
                            "duplicate metric id ${metric.id}"
                        }
                        id = null
                        type = null
                    }
                }
                check(depth == 0) { "unterminated metric in $path" }
            }
    }
    return metrics.values.sortedBy { it.id }
}

private fun javaSource(metrics: List<Metric>): String = buildString {
    appendLine("// DO NOT EDIT THIS FILE")
    appendLine("// This is auto-generated from the AOSP express metric catalog")
    appendLine()
    appendLine("package com.android.modules.expresslog;")
    appendLine()
    appendLine("import android.util.ArrayMap;")
    appendLine()
    appendLine("public final class MetricIds {")
    appendLine("    public static final long INVALID_METRIC_ID = 0;")
    appendLine("    public static final int METRIC_TYPE_UNKNOWN = 0;")
    appendLine("    public static final int METRIC_TYPE_COUNTER = 1;")
    appendLine("    public static final int METRIC_TYPE_HISTOGRAM = 2;")
    appendLine("    public static final int METRIC_TYPE_COUNTER_WITH_UID = 3;")
    appendLine("    public static final int METRIC_TYPE_HISTOGRAM_WITH_UID = 4;")
    appendLine()
    appendLine("    private static final class MetricInfo {")
    appendLine("        MetricInfo(long hash, int type) { mHash = hash; mType = type; }")
    appendLine("        final long mHash;")
    appendLine("        final int mType;")
    appendLine("    }")
    appendLine()
    appendLine("    private static final ArrayMap<String, MetricInfo> metricIds = new ArrayMap<>();")
    appendLine("    static {")
    val hash = Hashing.farmHashFingerprint64()
    metrics.forEach { metric ->
        val value = hash.hashString(metric.id, StandardCharsets.UTF_8).asLong()
        appendLine("        metricIds.put(\"${metric.id}\", new MetricInfo(${value}L, ${metric.type}));")
    }
    appendLine("    }")
    appendLine()
    appendLine("    static long getMetricIdHash(String metricId, int type) {")
    appendLine("        MetricInfo info = metricIds.get(metricId);")
    appendLine("        if (info == null || info.mType != type) return INVALID_METRIC_ID;")
    appendLine("        return info.mHash;")
    appendLine("    }")
    appendLine("}")
}

fun main(args: Array<String>) {
    require(args.size == 2) { "usage: generate-express-metric-ids <catalog-dir> <output.java>" }
    Files.writeString(Path.of(args[1]), javaSource(readCatalog(Path.of(args[0]))))
}
