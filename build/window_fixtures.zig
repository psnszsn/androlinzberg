//! A real Kotlin APK for task/window lifecycle regressions, compiled separately
//! from the hosted framework. Its checksum is recorded in the testkit registry.
const std = @import("std");
const command = @import("command.zig");
pub const Result = struct { apk: std.Build.LazyPath, registry: std.Build.LazyPath };
pub fn build(b: *std.Build, aosp: *std.Build.Dependency, framework: @import("java.zig").Result) Result {
    const kotlinc = command.create(b);
    kotlinc.addFileArg(aosp.path("external/kotlinc/bin/kotlinc"));
    kotlinc.addArgs(&.{ "-no-jdk", "-no-stdlib", "-no-reflect", "-language-version", "2.0", "-api-version", "2.0", "-jvm-target", "21", "-Xsam-conversions=class", "-Xstring-concat=inline", "-classpath" });
    kotlinc.addJoinedPaths(":", &.{ framework.compile_boot_jar, framework.classes_jar, aosp.path("external/kotlinc/lib/kotlin-stdlib.jar") });
    kotlinc.addArg("-d");
    const classes = kotlinc.addOutputFileArg("window-fixture-classes.jar");
    kotlinc.addFileArg(b.path("src/java/dev/artzig/fixtures/windows/WindowFixtureActivity.kt"));
    kotlinc.addFileArg(b.path("src/java/dev/artzig/fixtures/windows/TextureFixtureActivity.kt"));
    kotlinc.addFileArg(b.path("src/java/dev/artzig/fixtures/windows/VideoFixtureActivity.kt"));
    kotlinc.addFileArg(b.path("src/java/dev/artzig/fixtures/windows/ImeFixtureActivity.kt"));
    kotlinc.addFileArg(b.path("src/java/dev/artzig/fixtures/windows/ClipboardFixtureActivity.kt"));
    kotlinc.addFileArg(b.path("src/java/dev/artzig/fixtures/windows/ColdProcessFixture.kt"));
    const d8 = b.addSystemCommand(&.{ "java", "-Xmx512M", "-cp" });
    d8.addFileArg(aosp.path("prebuilts/r8/r8.jar"));
    d8.addArgs(&.{ "com.android.tools.r8.D8", "--min-api", "35", "--lib" });
    d8.addFileArg(framework.compile_boot_jar);
    d8.addArg("--classpath");
    d8.addFileArg(framework.classes_jar);
    d8.addArg("--output");
    const dex = d8.addOutputFileArg("window-fixture-dex.jar");
    d8.addFileArg(classes);
    d8.addFileArg(aosp.path("external/kotlinc/lib/kotlin-stdlib.jar"));
    const link = b.addSystemCommand(&.{ "aapt2", "link", "-o" });
    const resources = link.addOutputFileArg("window-fixture-res.apk");
    link.addArg("--manifest");
    link.addFileArg(b.path("testdata/fixture-apks/dev.artzig.fixtures.windows/AndroidManifest.xml"));
    link.addArg("-I");
    link.addFileArg(framework.resources.apk);
    link.addArgs(&.{ "--min-sdk-version", "35", "--target-sdk-version", "35" });
    const package = b.addSystemCommand(&.{"python3"});
    package.addFileArg(b.path("tools/window-fixture-apk.py"));
    package.addArg("package");
    package.addFileArg(resources);
    package.addFileArg(dex);
    const unsigned = package.addOutputFileArg("window-fixture-unsigned.apk");
    const signed = @import("generators.zig").signApk(b, aosp, unsigned, "window-fixture.apk", true, "azk-platform");
    const registry = b.addSystemCommand(&.{"python3"});
    registry.addFileArg(b.path("tools/window-fixture-apk.py"));
    registry.addArg("registry");
    registry.addFileArg(b.path("tests/apks.json"));
    registry.addFileArg(signed);
    const metadata = registry.addOutputFileArg("apks.json");
    const install = b.addInstallFile(signed, "test-fixtures/window-fixture.apk");
    b.step("window-fixture", "Build the Kotlin task/window contract APK").dependOn(&install.step);
    return .{ .apk = signed, .registry = metadata };
}
