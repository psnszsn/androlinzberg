#!/usr/bin/env bash
# Assemble a self-contained, relocatable ART runtime tree from the Soong output.
#
#   tools/install.sh [DEST]       (default: ./dist/art)
#
# Layout (mirrors AOSP's host layout so the $ORIGIN rpaths keep working):
#   DEST/bin/        dalvikvm64 dex2oat64 d8 (+ d8.jar) ...
#   DEST/lib64/      libart.so and every lib in its ldd/dlopen closure
#   DEST/apex/com.android.{art,i18n,conscrypt}/javalib/*.jar   boot classpath
#   DEST/apex/com.android.art/javalib/x86_64/boot*.{art,oat,vdex}  boot image
#   DEST/com.android.i18n/etc, DEST/com.android.tzdata/etc         ICU + tz data
#   DEST/framework/*-hostdex.jar                                    javac bootclasspath (classes)
#   DEST/runtime.env                                                launcher contract (sourceable)
#
# The boot image is generated with canonical /apex/... dex locations, so at
# runtime the launcher passes -Xbootclasspath:<real paths>
# -Xbootclasspath-locations:<canonical paths>. This keeps the tree movable.
set -euo pipefail
trap 'echo "install.sh: failed at line $LINENO: $BASH_COMMAND" >&2' ERR
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT=$ROOT/out/host/linux-x86
DEST=$(realpath -m "${1:-$ROOT/dist/art}")
ISA=x86_64

[ -x "$OUT/bin/dalvikvm64" ] || { echo "run tools/soong-build.sh build-art-host generate-boot-image-host d8-host first"; exit 1; }

rm -rf "$DEST"; mkdir -p "$DEST"/{bin,lib64,framework,apex}

# --- binaries
for b in dalvikvm64 dex2oat64 dexdump oatdump profman generate-boot-image64; do
  [ -e "$OUT/bin/$b" ] && cp "$OUT/bin/$b" "$DEST/bin/"
done
cp "$OUT/bin/d8" "$DEST/bin/d8"
cp "$OUT/framework/d8.jar" "$DEST/framework/" 2>/dev/null || cp "$(find "$OUT" -name d8.jar -print -quit)" "$DEST/framework/"
sed -i 's|^libdir="\$progdir"$|libdir="$progdir/../framework"|' "$DEST/bin/d8"

# --- shared libs: ldd closure of the binaries plus everything ART dlopen()s
dlopened="libjavacore.so libopenjdk.so libopenjdkjvm.so libjavacrypto.so libart-compiler.so
          libart-disassembler.so libicu_jni.so libicu.so libicui18n-host.so libicuuc-host.so
          libnativeloader.so libnativebridge.so libsigchain.so libartpalette.so libexpat-host.so
          libandroidio.so libopenjdkjvmti.so libadbconnection.so libdt_fd_forward.so libnpt.so libjdwp.so"
for l in $dlopened; do [ -e "$OUT/lib64/$l" ] && cp "$OUT/lib64/$l" "$DEST/lib64/"; done
# walk the closure using the out/ copies (their rpaths resolve siblings)
want="$OUT/bin/dalvikvm64 $OUT/bin/dex2oat64"; for l in $dlopened; do [ -e "$OUT/lib64/$l" ] && want+=" $OUT/lib64/$l"; done
seen=""
while [ -n "$want" ]; do
  next=""
  for f in $want; do
    for p in $(ldd "$f" 2>/dev/null | awk '/=> \// {print $3}' | grep "^$OUT/" || true); do
      p=$(realpath "$p"); b=$(basename "$p")
      case " $seen " in *" $b "*) ;; *) seen+=" $b"; next+=" $p"; cp -n "$p" "$DEST/lib64/";; esac
    done
  done
  want=$next
done
echo "libs: $(ls "$DEST/lib64" | wc -l)"

# --- boot classpath jars (dex), in AOSP apex layout
cp -r "$OUT/apex/com.android.art" "$OUT/apex/com.android.i18n" "$OUT/apex/com.android.conscrypt" "$DEST/apex/"
# --- ICU / tz data
cp -r "$OUT/com.android.i18n" "$OUT/com.android.tzdata" "$DEST/"
# --- class jars for compiling against (javac -bootclasspath)
for j in core-oj core-libart okhttp bouncycastle apache-xml core-icu4j conscrypt; do
  src=$(find "$ROOT/out/soong/.intermediates" -path "*/$j/android_common/javac/$j.jar" -print -quit 2>/dev/null)
  if [ -n "$src" ]; then cp "$src" "$DEST/framework/$j-classes.jar"; else echo "warning: no classes jar for $j"; fi
done

# --- boot image
imgdir="$DEST/apex/com.android.art/javalib"
"$DEST/bin/generate-boot-image64" --output-dir="$imgdir" --compiler-filter=speed --use-profile=false \
   --dex2oat-bin="$DEST/bin/dex2oat64" --android-root="$DEST" --instruction-set=$ISA 2>&1 \
   > "$DEST/boot-image.log" 2>&1 || { tail -5 "$DEST/boot-image.log"; exit 1; }

# --- launcher contract
bcp=""; bcpl=""
for j in com.android.art/javalib/core-oj com.android.art/javalib/core-libart com.android.art/javalib/okhttp \
         com.android.art/javalib/bouncycastle com.android.art/javalib/apache-xml \
         com.android.i18n/javalib/core-icu4j com.android.conscrypt/javalib/conscrypt; do
  bcp+="\$ART_ROOT/apex/$j.jar:"; bcpl+="/apex/$j.jar:"
done
cat > "$DEST/runtime.env" <<ENV
# Source this (with ART_ROOT set to this directory) to get the environment
# and the VM options the ART host runtime needs. Generated by tools/install.sh.
export ANDROID_ROOT="\$ART_ROOT"
export ANDROID_ART_ROOT="\$ART_ROOT/apex/com.android.art"
export ANDROID_I18N_ROOT="\$ART_ROOT/com.android.i18n"
export ANDROID_TZDATA_ROOT="\$ART_ROOT/com.android.tzdata"
export ANDROID_DATA="\${ANDROID_DATA:-\${XDG_CACHE_HOME:-\$HOME/.cache}/artzig}"
ART_BOOTCLASSPATH="${bcp%:}"
ART_BOOTCLASSPATH_LOCATIONS="${bcpl%:}"
ART_VM_OPTS="-Xnorelocate -Ximage:\$ART_ROOT/apex/com.android.art/javalib/boot.art -Xbootclasspath:\$ART_BOOTCLASSPATH -Xbootclasspath-locations:\$ART_BOOTCLASSPATH_LOCATIONS"
ENV
cat > "$DEST/bin/art" <<'SH'
#!/usr/bin/env bash
# Convenience launcher: art [-Xopts] -cp foo.dex Main
ART_ROOT=$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)
export ART_ROOT
. "$ART_ROOT/runtime.env"
mkdir -p "$ANDROID_DATA/dalvik-cache/x86_64"
exec "$ART_ROOT/bin/dalvikvm64" $ART_VM_OPTS "$@"
SH
chmod +x "$DEST/bin/art"
echo "installed to $DEST ($(du -sh "$DEST" | cut -f1))"
